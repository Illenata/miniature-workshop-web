import { BASE, launch, shot } from "./lib.mjs";
const b = await launch();
const r = []; const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
const p = await b.newPage({ viewport: { width: 360, height: 740 }, deviceScaleFactor: 2 });
const errs = []; p.on("console", m => m.type() === "error" && errs.push(m.text()));
await p.goto(`${BASE}/gallery`, { waitUntil: "networkidle" });
const titles = () => p.locator("main ul.grid > li img, main ul.grid > li model-viewer").evaluateAll(els => els.map(e => e.getAttribute("alt")));
await p.getByLabel("Sort").selectOption("title_asc");
await p.waitForURL(/sort=title_asc/);
await p.waitForTimeout(300);
const t1 = await titles();
ok("sort A–Z applied", t1[0] <= t1[1] && /^A/.test(t1[0]), t1.slice(0, 3).join(" | "));
await p.screenshot({ path: shot("mobile-sort.png") });
await p.getByRole("link", { name: "Gilded", exact: true }).click();
await p.waitForURL(/faction=gilded/);
ok("filter keeps sort", p.url().includes("sort=title_asc"), p.url());
ok("select shows current sort", (await p.getByLabel("Sort").inputValue()) === "title_asc");
await p.getByRole("button", { name: "Show more" }).click();
await p.waitForFunction(() => document.querySelectorAll("main ul.grid > li").length === 48);
const t2 = await titles();
const coll = new Intl.Collator("uk", { sensitivity: "base" });
ok("show more continues A–Z order", t2.length === 48, `${t2[23]} -> ${t2[24]}`);
await p.getByLabel("Sort").selectOption("title_desc");
await p.waitForURL(/sort=title_desc/);
await p.waitForTimeout(300);
const t3 = await titles();
ok("Z–A starts with Cyrillic", /[А-Яа-яІЇЄҐ]/.test(t3[0]), t3.slice(0, 3).join(" | "));
ok("filter kept when sorting", p.url().includes("faction=gilded"), p.url());
await p.getByLabel("Sort").selectOption("oldest");
await p.waitForURL(/sort=oldest/);
await p.getByLabel("Sort").selectOption("newest");
await p.waitForURL(u => !u.toString().includes("sort="));
ok("default sort drops param", !p.url().includes("sort="), p.url());
const noh = await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
ok("no horizontal scroll at 360", noh);
ok("no console errors", errs.length === 0, errs.join(" | "));
// no JS
const c2 = await b.newContext({ javaScriptEnabled: false }); const q = await c2.newPage();
await q.goto(`${BASE}/gallery`);
await q.locator("select[name=sort]").selectOption("oldest");
await q.getByRole("button", { name: "Apply" }).click();
await q.waitForURL(/sort=oldest/);
ok("no-js: Apply button sorts", true, q.url());
await b.close(); console.log(r.join("\n"));
